MachinelikeK500Controller::MachinelikeK500Controller(hid_device* dev_cmd_handle, hid_device* dev_data_handle, const char* path, const std::string& dev_name)
{
    dev_cmd  = dev_cmd_handle;
    dev_data = dev_data_handle;
    name            = dev_name;

    led_count       = 95;

    current_mode    = MODE_PER_KEY;
    current_speed   = SPEED_NORMAL;

    location        = path;
}

MachinelikeK500Controller::~MachinelikeK500Controller()
{
    hid_close(dev_cmd);
    hid_close(dev_data);
}

std::string MachinelikeK500Controller::GetLocation()
{
    return("HID: " + location);
}

std::string MachinelikeK500Controller::GetName()
{
    return(name);
}

unsigned char MachinelikeK500Controller::GetCurrentMode()
{
    return current_mode;
}

unsigned int MachinelikeK500Controller::GetLEDCount()
{
    return(sizeof(tkl_keys_per_key_index) / sizeof(*tkl_keys_per_key_index));
}

std::string MachinelikeK500Controller::GetSerialString()
{
    wchar_t serial_string[128];
    int ret = hid_get_serial_number_string(dev_cmd, serial_string, 128);

    if(ret != 0)
    {
        return("");
    }

    return(StringUtils::wstring_to_string(serial_string));
}

void MachinelikeK500Controller::SetLEDsDirect(std::vector<RGBColor> colors)
{
    const int buf2=382;
    unsigned char usb_buf2[buf2];
    unsigned int num_keys = 95;

    memset(usb_buf2, 0x00, sizeof(usb_buf2));

    usb_buf2[0]   = 0x08;
    usb_buf2[1]   = 0x0A;
    usb_buf2[2]   = 0x7A;
    usb_buf2[3]   = 0x01;

    for(unsigned int i = 0; i < num_keys; i++)
    {
        usb_buf2[tkl_keys_per_key_index[i]]     = RGBGetRValue(colors[i]);
        usb_buf2[tkl_keys_per_key_index[i] + 1] = RGBGetGValue(colors[i]);
        usb_buf2[tkl_keys_per_key_index[i] + 2] = RGBGetBValue(colors[i]);
    }

    hid_send_feature_report(dev_data, usb_buf2, sizeof(usb_buf2));
}


void MachinelikeK500Controller::SetMode(unsigned char /*mode*/, unsigned char /*brightness*/, unsigned char /*speed*/, unsigned char /*color_mode*/)
{
    const int buf2=382;
    unsigned char usb_buf2[buf2];
    memset(usb_buf2, 0x00, sizeof(usb_buf2));
    usb_buf2[0]=0x08;
    usb_buf2[1]=0x0A;
    usb_buf2[2]=0x7A;
    usb_buf2[3]=0x01;
    if(hid_send_feature_report(dev_data, usb_buf2, sizeof(usb_buf2)) > -1)
    {
        memset(usb_buf2, 0x00, sizeof(usb_buf2));
    }
}

